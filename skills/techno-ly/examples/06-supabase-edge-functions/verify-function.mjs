import fs from 'node:fs';
import assert from 'node:assert/strict';
import {transform} from 'esbuild';
let handler;
globalThis.Deno={serve:fn=>{handler=fn}};
const src=fs.readFileSync('example/supabase/functions/apply-coupon/index.ts','utf8');
const built=await transform(src,{loader:'ts',format:'esm'});
await import('data:text/javascript;base64,'+Buffer.from(built.code).toString('base64'));
const call=async(body)=>{const r=await handler(new Request('http://localhost/apply-coupon',{method:'POST',body:JSON.stringify(body),headers:{'content-type':'application/json'}}));return {status:r.status,data:await r.json()}};
assert.deepEqual((await call({code:'TAQNI20'})).data,{valid:true,originalPrice:100,discount:20,finalPrice:80,currency:'LYD'});
assert.equal((await call({code:'TEST'})).status,400);
assert.equal((await call({code:'TEST'})).data.finalPrice,100);
assert.equal((await call({code:'TAQNI20',originalPrice:1,discountRate:1})).data.finalPrice,80);
assert.equal((await call({code:' taqni20 '})).data.finalPrice,80);
assert.equal((await call({code:123})).status,400);
assert.equal((await handler(new Request('http://localhost',{method:'OPTIONS'}))).status,204);
assert.equal((await handler(new Request('http://localhost'))).status,405);
assert.equal((await handler(new Request('http://localhost',{method:'POST',body:'{'}))).status,400);
console.log('PASS: valid coupon, invalid coupon, server-owned price, normalization, invalid type, preflight, method, malformed JSON');
